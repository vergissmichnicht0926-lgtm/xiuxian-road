function buildPlayerContext() {
  let moodHint = '';
  if (G.mood <= 30) moodHint = '最近情绪有些低落，校园生活蒙上了一层灰色。';
  else if (G.mood >= 70) moodHint = '最近心情很好，每天都能发现校园里的小确幸。';
  let energyHint = '';
  if (G.energy <= 20) energyHint = '最近感到很疲惫，可能太勉强自己了。';
  let moneyHint = '';
  if (G.money < 50) moneyHint = '最近零花钱不多了，开销需要精打细算。';
  let gradeHint = '';
  if (G.turnsSinceStudy >= 2) gradeHint = '最近成绩有所下滑，可能需要多花时间学习。';
  let recoveryHint = '';
  if (G.mood <= 25) recoveryHint = '【重要】玩家心情很低落，事件应带有"转机"意味——让一个角色注意到主角的状态并主动关心，给予温暖的互动。';

  const hints = [moodHint, energyHint, moneyHint, gradeHint].filter(Boolean).join('');

  return `【玩家状态】
成绩:${G.grade} 体力:${G.energy} 心情:${G.mood} 零花钱:${G.money}円
${G.lover ? `恋人：${getCharacter(G.lover)?.name || '?'}` : '单身'}
${hints ? `【状态提示】${hints}` : ''}
${recoveryHint}`;
}

function buildCharacterContext(includeAll = false) {
  const chars = includeAll ? getAllCharacters() : getCoreCharacters();
  if (!chars.length) return '【已认识的人】还没有认识任何人。';

  let s = '【已认识的人】\n';
  for (const c of chars) {
    const isLover = G.lover === c.id;
    s += `- [ID:${c.id}] ${c.name}（${c.gender}·${c.grade}·${c.club || '无社团'}）性格:${c.personality.join(',')} 好感:${c.affinity} 关系:${getRelationLabel(c, isLover)}\n`;
    if (c.history.length) {
      s += `  关系关键事件：${c.history.slice(-3).map(h => h.event).join('；')}\n`;
    }
  }
  if (G.recentCharacterTags.length) {
    s += `\n【避免生成以下类型的角色】标签：${G.recentCharacterTags.join(', ')}`;
  }
  return s;
}

function buildProfileContext() {
  const p = G.player;
  let s = `【主角档案】
姓名：${p.name}，性别：${p.gender}
性格：${p.personality}，生活重心：${p.focus}
性取向：${p.orientation}
转校原因：${p.transferReason}
当前心情：${G.mood}`;

  // 人设信息（v0.4）—— NPC会根据你的外观/爱好/特长做出不同反应
  if (p.appearance) s += `\n外观：${p.appearance}`;
  if (p.hobbies) s += `\n爱好：${p.hobbies}`;
  if (p.talent) s += `\n擅长：${p.talent}`;
  if (p.weakness) s += `\n不擅长：${p.weakness}`;
  if (p.clubPreference) s += `\n社团倾向：${p.clubPreference}`;
  if (p.birthday) s += `\n生日：${p.birthday}`;
  if (p.bio) s += `\n人设小传：${p.bio}`;

  return s;
}

